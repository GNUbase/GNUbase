#!/bin/sh
# SPDX-License-Identifier: GPL-3.0-or-later
# Makes Git run the hooks in tools/git-hooks for this clone and all its worktrees. Run once per clone.
# Usage: tools/install-git-hooks.sh [--maintainer]
#
# pre-commit and commit-msg block commits that contain a keyword from the private list in .git/info/private-keywords.
# Maintainers have that list. When it is present, or with --maintainer, the clone is marked so that a missing list
# blocks every commit instead of skipping the scan. Contributors don't have the list; their commits are not scanned
# locally, and CI scans every pull request (.github/workflows/keyword-scan.yml).
#
# core.hooksPath replaces .git/hooks, so tools/git-hooks also has the Git LFS hooks, as our own scripts that call
# git-lfs. Copies of git-lfs's generated hooks would not do: their text changes between git-lfs versions, and git-lfs
# rewrites or rejects hooks generated by other versions. This script sets up Git LFS for the clone without hooks;
# a plain `git lfs install` inside the clone also works, but complains that the hooks already exist.
#
# Git runs no hooks while a commit from before tools/git-hooks existed is checked out, because the folder is missing
# there. Merge main into older branches before committing on them.
set -eu
cd "$(git rev-parse --show-toplevel)"

maintainer=false
case "${1:-}" in
--maintainer) maintainer=true ;;
"") ;;
*)
	echo "Usage: $0 [--maintainer]" >&2
	exit 2
	;;
esac

list="$(git rev-parse --git-common-dir)/info/private-keywords"
[ -e "$list" ] && maintainer=true

# Relative to the top of the worktree the hooks run in, so every worktree uses its own checkout's hooks.
git config core.hooksPath tools/git-hooks
echo "Git hooks installed: core.hooksPath = tools/git-hooks"

if command -v git-lfs > /dev/null 2>&1; then
	git lfs install --local --skip-repo > /dev/null
	echo "Git LFS set up for this clone"
else
	echo "git-lfs is not installed: install it, then run this script again. Pushing is blocked until then." >&2
fi

if [ "$maintainer" = true ]; then
	git config gnubase.requireKeywordList true
fi
if [ -e "$list" ]; then
	echo "Keyword guard active with $(tr -d '\r' < "$list" | grep -c .) keywords from $list"
elif [ "$(git config --bool gnubase.requireKeywordList || true)" = true ]; then
	echo "Commits are blocked until the keyword list is at $list: copy it from another maintainer clone."
else
	echo "No keyword list at $list, so commits are not scanned locally; CI scans every pull request."
fi
